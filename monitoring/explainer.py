"""Разбор: длинный пост-объяснение по одной теме, дважды в день.

Отличается от новости не длиной, а задачей. Новость сообщает, что случилось.
Разбор отвечает на вопрос «что мне с этим делать» — и потому обязан содержать
конкретные шаги, а не пересказ.

Структура взята с образца, который дал заказчик, и повторяется намеренно:
читатель канала привыкает к форме и находит нужное, не перечитывая целиком.

    что вступает в силу и когда
    что из-за этого меняется на площадке
    кого касается, а кого нет
    что это вообще такое, если термин незнаком
    📌 Что нужно сделать — по пунктам
    нюансы и исключения
    короткий призыв проверить у себя

Источников у разбора несколько: одна новость даёт повод, но не даёт глубины.
Собираются все находки той же темы за окно наблюдения, и модель пишет
по их совокупному тексту.

Числа проверяются так же, как в новостном посте, и по той же причине:
выдуманный срок или процент в инструкции «что делать» дороже отсутствия
инструкции. Проверка живёт в monitoring/writer.py и переиспользуется здесь.
"""
from monitoring.writer import unsupported_numbers

# Разбор длиннее новости, и текста-основы ему нужно больше: по одному абзацу
# инструкцию не напишешь, а попытка — это сочинительство.
MIN_SOURCE_CHARS = 1200
SOURCE_LIMIT = 14000
MAX_LENGTH = 4096          # предел сообщения Телеграма

INSTRUCTION = """Ты пишешь разбор для Телеграм-канала о маркетплейсах.
Читают продавцы: они принимают решения о деньгах, сроках и товаре.

Разбор — это не пересказ новости. Это ответ на вопрос «что мне с этим
делать». Если из материала не следует ни одного действия продавца,
так и напиши в конце, а не выдумывай действие.

Жёсткие правила:
1. Пиши ТОЛЬКО о том, что есть в исходных материалах. Ничего не додумывай.
2. Не выдумывай числа, проценты, даты, сроки, номера законов и статей.
   Каждая цифра обязана быть в исходном тексте.
3. Не выдумывай ссылки и названия сервисов, которых в материалах нет.
4. Не обещай последствий, которых в материалах нет.

Структура — держись её:
- Первая строка: заголовок разбора, коротко и по делу.
- Что меняется и с какого числа.
- Кого это касается, а кого нет.
- Если есть незнакомый термин — объясни его одним абзацем.
- Строка «📌 Что нужно сделать?» и дальше конкретные шаги.
- Нюансы и исключения, если они есть в материалах, маркером ▪️
- Последняя строка: короткий призыв проверить у себя.

Как писать:
- Живой человеческий язык, короткие предложения, без канцелярита.
- Абзацы по 1–3 предложения, между ними пустая строка.
- Без хештегов, без «друзья» и «коллеги», без воды во вступлении.
- От 1500 до 3000 знаков.

Верни ТОЛЬКО текст разбора. Без пояснений и без кавычек вокруг.
"""


def gather_sources(materials: list) -> str:
    """Склеивает тексты материалов в основу для разбора.

    Один материал — это повод, но не глубина: официальное уведомление
    говорит, что меняется, а разбор отраслевого издания — чем это грозит.
    Вместе они дают инструкцию, порознь — пересказ.
    """
    blocks = []
    for material in materials:
        text = (material.get("text") or "").strip()
        if not text:
            continue
        blocks.append(f"--- {material.get('title', 'без заголовка')}\n"
                      f"{material.get('url', '')}\n{text}")
    return "\n\n".join(blocks)[:SOURCE_LIMIT]


def build_prompt(topic: str, source: str) -> str:
    return f"{INSTRUCTION}\nТема разбора: {topic}\n\nМатериалы:\n{source}\n"


def write_explainer(topic: str, source: str, client, attempts: int = 2):
    """Разбор по теме и материалам. Возвращает WriteResult из writer."""
    from monitoring.writer import WriteResult

    if len((source or "").strip()) < MIN_SOURCE_CHARS:
        return WriteResult(reason="материалов не хватает на разбор "
                                  f"({len((source or '').strip())} знаков)")
    if client is None:
        return WriteResult(reason="нет ключа модели (OPENROUTER_API_KEY)")

    prompt = build_prompt(topic, source)
    invented = []
    for _ in range(attempts):
        if invented:
            prompt = (f"{prompt}\n\nВ прошлый раз ты написал числа, которых "
                      f"нет в материалах: {', '.join(invented)}. "
                      f"Перепиши без них.")
        try:
            text = (client.complete(prompt) or "").strip()
        except Exception as exc:
            return WriteResult(reason=f"модель не ответила: {exc}")
        if not text:
            continue

        invented = unsupported_numbers(text, source)
        if not invented:
            return WriteResult(text=text[:MAX_LENGTH])

    if invented:
        return WriteResult(reason="числа, которых нет в материалах: "
                                  + ", ".join(invented))
    return WriteResult(reason="модель вернула пустой ответ")
