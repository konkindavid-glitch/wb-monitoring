"""Фон обложки, нарисованный моделью через OpenRouter.

Картинка генерируется БЕЗ текста, заголовок наносится своим шрифтом поверх —
в monitoring/cover.py. Причин две, и обе практические.

Первая: модели изображений плохо рисуют кириллицу. Буквы выходят похожими
на русские, но словами не являются — обложка с «ХРАНЕНNЯ» хуже, чем совсем
без картинки. Своим шрифтом текст выходит точным всегда.

Вторая: заголовок на обложке обязан совпадать с заголовком материала. Модель,
которой доверили нарисовать надпись, пишет своё приближение — и обложка
начинает обещать не то, что в посте.

Про содержание. В подсказке запрещены логотипы и узнаваемые вывески: рисовать
фирменный знак реальной компании на выдуманном снимке нельзя. По той же
причине запрещены документальные сцены конкретных происшествий — пожаров,
разрушений, аварий: сгенерированный «снимок горящего склада» читатель примет
за фотографию с места события, которого в таком виде не было. Для таких тем
остаётся настоящее фото из статьи или фирменная плашка.
"""
import base64
import os
import re

MODEL = "google/gemini-2.5-flash-image"
URL = "https://openrouter.ai/api/v1/chat/completions"
TIMEOUT = 120.0

_DATA_URI = re.compile(r"data:image/(?:png|jpe?g|webp);base64,([A-Za-z0-9+/=]+)")

# Темы, для которых сцена не выдумывается: сгенерированную «фотографию»
# конкретного происшествия примут за съёмку с места.
SENSITIVE = re.compile(
    r"пожар|сгор|горит|возгоран|взрыв|атак|удар|дрон|бпла|обстрел|"
    r"погиб|пострадавш|пострадав|жертв|разрушен|обрушен|авари|теракт",
    re.I)

SCENE = """Сгенерируй фотореалистичное редакционное изображение
вертикального формата 4:5 для новостного поста о торговых площадках.

Сюжет: {scene}

Требования:
- Никакого текста, букв, цифр, надписей и водяных знаков на изображении.
- Никаких логотипов и узнаваемых фирменных вывесок реальных компаний.
- Никаких людей крупным планом и узнаваемых лиц.
- Спокойный деловой свет, приглушённые тона, глубина резкости.
- Нижняя треть кадра — спокойная и малодетальная: туда ляжет заголовок.
"""

# Сюжет по теме, а не по заголовку: пересказывать заголовок картинкой значит
# просить модель проиллюстрировать конкретное событие, чего она не знает.
SCENES = {
    "logistics_warehouse": "современный распределительный склад, ряды стеллажей, "
                           "погрузочные ворота, паллеты",
    "seller_money": "рабочий стол продавца: ноутбук с графиками, калькулятор, "
                    "коробки на фоне",
    "rules_offer": "офисный стол с документами и печатью, строгий свет",
    "advertising": "экран с рекламной аналитикой на рабочем столе",
    "algorithms_tech": "серверная стойка, индикаторы, холодный свет",
    "ai_marketplace": "абстрактная визуализация нейросети над складом",
    "regulation": "здание в строгой классической архитектуре, деловой квартал",
    "disputes": "переговорная комната, папки с документами",
    "seller_cases": "небольшой склад предпринимателя, коробки, стол упаковки",
    "incidents_scandals": "пустой склад в холодном свете, приглушённые тона",
    "market_trends": "витрина пункта выдачи заказов, поток покупателей вдалеке",
}
DEFAULT_SCENE = ("современный логистический комплекс электронной торговли, "
                 "фуры у ворот, пасмурный день")


def is_sensitive(hit: dict) -> bool:
    """Тема, для которой выдуманная «фотография» была бы подлогом."""
    return bool(SENSITIVE.search(hit.get("title") or ""))


def scene_for(hit: dict) -> str:
    for topic in hit.get("topics") or []:
        if topic in SCENES:
            return SCENES[topic]
    return DEFAULT_SCENE


def build_prompt(hit: dict) -> str:
    return SCENE.format(scene=scene_for(hit))


def extract_image(payload: dict) -> bytes:
    """Картинка из ответа OpenRouter. Пусто, если её там нет.

    Разные модели кладут её по-разному — в message.images, в content
    или в отдельное поле. Поэтому ищется data-URI в тексте всего ответа:
    ловить конкретную форму значило бы ломаться при смене модели.
    """
    import json

    found = _DATA_URI.search(json.dumps(payload))
    if not found:
        return b""
    try:
        return base64.b64decode(found.group(1))
    except Exception:
        return b""


def generate(hit: dict, client=None) -> bytes:
    """Фон для обложки или пусто. Никогда не бросает.

    Пустой результат — не ошибка: обложка обойдётся фотографией из статьи
    или фирменной плашкой, а пост уйдёт в любом случае.
    """
    key = os.getenv("OPENROUTER_API_KEY")
    if not key:
        return b""
    if is_sensitive(hit):
        print("[cover] тема чувствительная — картинку не генерирую")
        return b""

    if client is None:
        from monitoring.net import plain_client
        client = plain_client(TIMEOUT)

    try:
        response = client.post(
            URL,
            headers={"Authorization": f"Bearer {key}",
                     "Content-Type": "application/json",
                     "HTTP-Referer": "https://amvera.ru",
                     "X-Title": "Monitoring Map"},
            json={"model": os.getenv("IMAGE_MODEL", MODEL),
                  "modalities": ["image", "text"],
                  "messages": [{"role": "user", "content": build_prompt(hit)}]})
        if response.status_code != 200:
            print(f"[cover] генератор ответил {response.status_code}: "
                  f"{response.text[:200]}")
            return b""
        return extract_image(response.json())
    except Exception as exc:
        print(f"[cover] генератор недоступен: {exc}")
        return b""
