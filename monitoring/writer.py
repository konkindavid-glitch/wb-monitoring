"""Текст поста по находке.

Пост пишется только по настоящему тексту материала. У находки есть заголовок
и ссылка; написать пост по одному заголовку — значит сочинить содержание.
Поэтому сначала забирается страница, и лишь потом модель пересказывает её
для селлеров. Не отдалась страница — поста не будет, и редактор увидит почему.

Числа проверяются механически, после модели. Выдуманный процент или срок
в посте для селлеров — это не стилистическая помарка: человек по нему
пересчитает себестоимость или пропустит срок. Модель, пересказывая, охотно
округляет и достраивает — поэтому каждое число из поста обязано найтись
в исходном тексте, иначе пост отклоняется.
"""
import re

# Меньше этого текст страницы не несёт содержания: это заглушка, капча
# или страница, отдавшая одну навигацию.
MIN_SOURCE_CHARS = 400
SOURCE_LIMIT = 6000
# Верхняя граница — предел сообщения Телеграма, а не подписи к фото:
# длинный пост уедет отдельным сообщением под обложкой, это умеет send_card.
# Просить у модели 900 знаков и резать по 1024 значило бы рвать текст
# на полуслове ровно в тех редких случаях, когда она не уложилась.
POST_LIMIT = 4096

_NUMBER = re.compile(r"\d[\d\u00a0\u202f ]*\d|\d")
_SEPARATORS = str.maketrans("", "", "\u00a0\u202f ")

INSTRUCTION = """Ты пишешь пост для Телеграм-канала о маркетплейсах.
Читают продавцы: они принимают решения о деньгах, сроках и товаре.

Главный вопрос, на который пост обязан отвечать:
продавец прочитал — он заработает, не потеряет деньги, избежит риска
или быстрее примет решение?

Жёсткие правила:
1. Пиши ТОЛЬКО о том, что есть в исходном тексте. Ничего не додумывай.
2. Не выдумывай числа, проценты, даты и сроки. Каждая цифра в посте обязана
   быть в исходном тексте. Нет цифры в источнике — не пиши цифру.
3. Не обещай последствий, которых в источнике нет.
4. Если в источнике чего-то нет — просто не пиши об этом.

Как писать:
- Первая строка — суть одним предложением, без «сегодня стало известно».
- Дальше 2–4 коротких абзаца: что меняется, кого касается, с какого момента.
- Последний абзац — что с этим делать продавцу. Конкретно.
- Без эмодзи в начале строк, без хештегов, без «друзья» и «коллеги».
- Живой человеческий язык, короткие предложения. Не пресс-релиз.
- Уложись в 900 знаков.

Верни ТОЛЬКО текст поста. Без заголовка «Пост:», без кавычек, без пояснений.
"""


def article_text(url: str, fetcher) -> str:
    """Читаемый текст страницы. Пустая строка, если источник не отдался."""
    from monitoring.collectors.doc_diff import normalize_dom

    try:
        result = fetcher.get(url)
    except Exception:
        return ""
    if result.status != 200 or not result.text:
        return ""
    return normalize_dom(result.text)[:SOURCE_LIMIT]


def build_prompt(hit: dict, source: str) -> str:
    return (f"{INSTRUCTION}\n"
            f"Заголовок материала: {hit.get('title', '')}\n"
            f"Ссылка: {hit.get('url', '')}\n\n"
            f"Исходный текст:\n{source}\n")


def numbers(text: str) -> set:
    """Числа как последовательности цифр, без разделителей разрядов.

    «1 500» и «1500» — одно и то же число, и придираться к пробелу,
    который поставила модель, значило бы браковать верные посты.
    """
    return {match.group(0).translate(_SEPARATORS)
            for match in _NUMBER.finditer(text or "")}


def unsupported_numbers(post: str, source: str) -> list:
    """Числа поста, которых нет в источнике. Пусто — пост можно публиковать."""
    haystack = (source or "").translate(_SEPARATORS)
    return sorted(n for n in numbers(post) if n not in haystack)


class WriteResult:
    """Итог написания: текст либо причина отказа, но не пустое молчание."""

    def __init__(self, text: str = None, reason: str = None):
        self.text = text
        self.reason = reason

    def __bool__(self):
        return bool(self.text)


def write_post(hit: dict, source: str, client, attempts: int = 2) -> WriteResult:
    """Пост по находке и тексту источника.

    При выдуманных числах делается ещё одна попытка с прямым указанием,
    какие именно цифры не найдены в источнике: чаще всего модель их просто
    убирает. Второй промах — отказ, а не публикация «почти правильного».
    """
    if len((source or "").strip()) < MIN_SOURCE_CHARS:
        return WriteResult(reason="источник не отдал текст статьи")
    if client is None:
        return WriteResult(reason="нет ключа модели (OPENROUTER_API_KEY)")

    prompt = build_prompt(hit, source)
    invented = []
    for attempt in range(attempts):
        if invented:
            prompt = (f"{prompt}\n\nВ прошлый раз ты написал числа, которых нет "
                      f"в исходном тексте: {', '.join(invented)}. "
                      f"Перепиши без них.")
        try:
            text = (client.complete(prompt) or "").strip()
        except Exception as exc:
            return WriteResult(reason=f"модель не ответила: {exc}")
        if not text:
            continue

        invented = unsupported_numbers(text, source)
        if not invented:
            return WriteResult(text=text[:POST_LIMIT])

    if invented:
        return WriteResult(reason="числа, которых нет в источнике: "
                                  + ", ".join(invented))
    return WriteResult(reason="модель вернула пустой ответ")
